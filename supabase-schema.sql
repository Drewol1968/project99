-- PROJECT 99 global daily ranking (Supabase/Postgres)
-- Run this once in Supabase SQL Editor.

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  challenge_date date not null,
  expression text not null check (expression in ('surprise','smile','wink','angry','kiss')),
  score numeric(4,1) not null check (score >= 0 and score <= 99.9),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, challenge_date, expression)
);

create index if not exists scores_daily_rank_idx
  on public.scores (challenge_date, expression, score desc);

alter table public.scores enable row level security;

revoke all on table public.scores from anon, authenticated;
grant select, insert, update on table public.scores to authenticated;

drop policy if exists "authenticated can read ranking" on public.scores;
create policy "authenticated can read ranking"
on public.scores for select
to authenticated
using (true);

drop policy if exists "users insert own score" on public.scores;
create policy "users insert own score"
on public.scores for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "users update own score" on public.scores;
create policy "users update own score"
on public.scores for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);
